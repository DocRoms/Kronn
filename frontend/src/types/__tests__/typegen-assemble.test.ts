// KT-1761 — the assembler's OUTPUT must be a pure function of its inputs: same
// bindings → same bytes, in a locale-independent order, and a stale bindings
// dir (one type declared two different ways) is refused, never half-merged.
// The "committed file == fresh regeneration" gate itself is `make typegen-check`
// locally and the `--check` step of ci-test.yml (it needs the ts-rs export).
import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { mkdtempSync, mkdirSync, writeFileSync, rmSync, readFileSync } from 'node:fs';
import { execFileSync, spawnSync } from 'node:child_process';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';
// @ts-expect-error no declaration file for the build script
import { assembleGenerated as assembleRaw, HEADER } from '../../../scripts/assemble-generated-types.mjs';

type Assembled = { content: string; count: number };
const assembleGenerated = assembleRaw as (bindings: string, rust: string) => Assembled;
const header = HEADER as string;

const SCRIPT = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..', 'scripts', 'assemble-generated-types.mjs');
const TS_RS = '// This file was generated by [ts-rs](https://github.com/Aleph-Alpha/ts-rs). Do not edit this file manually.\n';

let root: string;
let bindings: string;
let rust: string;

const binding = (file: string, body: string) => {
  mkdirSync(dirname(join(bindings, file)), { recursive: true });
  writeFileSync(join(bindings, file), `${TS_RS}\n${body}\n`);
};

beforeEach(() => {
  root = mkdtempSync(join(tmpdir(), 'typegen-'));
  bindings = join(root, 'bindings');
  rust = join(root, 'rust');
  mkdirSync(bindings);
  mkdirSync(rust);
});
afterEach(() => rmSync(root, { recursive: true, force: true }));

describe('assembleGenerated', () => {
  it('orders by type name in code-point order, whatever the file-system order', () => {
    // localeCompare would interleave these case-insensitively (a, B, c).
    binding('c.ts', 'export type c = string;');
    binding('B.ts', 'export type B = string;');
    binding('a.ts', 'export type a = string;');
    binding('Ab.ts', 'export type Ab = string;');
    const { content, count } = assembleGenerated(bindings, rust);
    const names = [...content.matchAll(/^export type (\w+) =/gm)].map(m => m[1]);
    expect(names).toEqual(['Ab', 'B', 'a', 'c']);
    expect(count).toBe(4);
    expect(content.startsWith(header)).toBe(true);
  });

  it('is byte-for-byte reproducible and does not depend on the dir layout', () => {
    binding('X.ts', 'export type X = { a: bigint, };');
    binding('sub/Y.ts', 'export type Y = string;');
    const first = assembleGenerated(bindings, rust).content;
    expect(assembleGenerated(bindings, rust).content).toBe(first);
    expect(first).toContain('export type X = { a: number, };'); // bigint → number
  });

  it('accepts a binding exported twice with identical content', () => {
    binding('Z.ts', 'export type Z = string;');
    binding('sub/Z.ts', 'export type Z = string;');
    expect(assembleGenerated(bindings, rust).count).toBe(1);
  });

  it('refuses a stale dir that declares one type two different ways', () => {
    binding('AgentsConfig.ts', 'export type AgentsConfig = { a: string, connection_fallbacks?: Array<string>, };');
    binding('old/AgentsConfig.ts', 'export type AgentsConfig = { a: string, };');
    expect(() => assembleGenerated(bindings, rust)).toThrow(/stale/);
  });
});

describe('assemble-generated-types.mjs --check', () => {
  const run = (...args: string[]) =>
    spawnSync('node', [SCRIPT, '--bindings', bindings, ...args], { encoding: 'utf8' });

  it('passes on a matching file and fails (exit 1, file untouched) on any difference', () => {
    binding('A.ts', 'export type A = string;');
    const out = join(root, 'generated.ts');
    execFileSync('node', [SCRIPT, '--bindings', bindings, '--out', out]);
    const generated = readFileSync(out, 'utf8');

    expect(run('--out', out, '--check').status).toBe(0);

    // a hand edit, then a dropped/extra type: both are drift
    writeFileSync(out, generated.replace('string', 'number'));
    const edited = run('--out', out, '--check');
    expect(edited.status).toBe(1);
    expect(edited.stderr).toContain('differs from a fresh regeneration');
    expect(readFileSync(out, 'utf8')).toContain('A = number');

    writeFileSync(out, generated);
    binding('B.ts', 'export type B = string;');
    expect(run('--out', out, '--check').status).toBe(1);
  });
});
