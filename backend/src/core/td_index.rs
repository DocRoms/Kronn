//! Deterministic tech-debt index: the `docs/tech-debt/TD-*.md` sheets are the
//! source of truth, and Kronn rewrites the `## Current list` table of
//! `docs/inconsistencies-tech-debt.md` from them after the audit steps, so
//! the findings of every sub-audit are reachable from the central index.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use crate::core::audit_validation::{index_status_decision, td_decision, TdDecision};

pub const CENTRAL_INDEX: &str = "inconsistencies-tech-debt.md";
const BLOCK_START: &str = "<!-- kronn:td-index:start (generated by Kronn from tech-debt/TD-*.md: edit the sheets, not this table) -->";
const BLOCK_START_PREFIX: &str = "<!-- kronn:td-index:start";
const BLOCK_END: &str = "<!-- kronn:td-index:end -->";
const UNKNOWN: &str = "Unknown";
const RESYNC_EVIDENCE: &str = "Kronn resync:";
const MAX_EVIDENCE_IDS: usize = 8;

/// One `TD-*.md` sheet, read from its front matter and header lines.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct TdSheet {
    pub id: String,
    pub title: String,
    pub area: String,
    pub severity: String,
    pub status: String,
    pub category: Option<String>,
    pub decision: Option<TdDecision>,
}

impl TdSheet {
    /// Rejected findings and accepted trade-offs are not active debt.
    pub fn is_active(&self) -> bool {
        self.decision.is_none_or(|d| !d.leaves_index())
    }
}

#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct ResyncOutcome {
    pub changed: bool,
    pub listed: usize,
    pub settled: usize,
    pub kept_without_sheet: usize,
    pub reconciled_dimensions: Vec<String>,
    /// Set when the index was left alone, with the reason.
    pub skipped: Option<String>,
    /// Sheets an accepted ADR settled before the rebuild (`TD → ADR`).
    pub adr_settled: Vec<String>,
    /// Sheets naming an ADR that is not in force (`TD → ADR`): still debt.
    pub adr_not_in_force: Vec<String>,
    /// Incomplete ADRs in `decisions.md`.
    pub adr_problems: Vec<String>,
    /// ADRs accepted during the run, set back to `proposed` for a human.
    pub adr_downgraded: Vec<String>,
}

/// The id of a `tech-debt/` file that counts as a sheet: `_`-prefixed reports
/// (`_reconciliation-*.md`) and scaffolding never do.
pub fn counted_sheet_stem(file_name: &str) -> Option<&str> {
    let stem = file_name.strip_suffix(".md")?;
    let scaffolding = matches!(file_name, "README.md" | "TEMPLATE.md");
    (is_sheet_id(stem) && !file_name.starts_with('_') && !scaffolding).then_some(stem)
}

/// Whether `value` can name a sheet file of `tech-debt/`: `TD-*` ids and the
/// detail files a dimension audit writes under its own prefix (`CQ-001`,
/// `PERF-2026…`). The review lists and settles every one the card counts
/// (KT-1309); only the `TD-` ones also feed the generated index.
pub fn is_sheet_id(value: &str) -> bool {
    !value.is_empty()
        && value.len() <= 100
        && value.starts_with(|c: char| c.is_ascii_alphanumeric())
        && value
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-' || b == b'_')
}

/// Whether a sheet's content is active debt, as the index and the counts read it.
pub fn content_is_active(id: &str, content: &str) -> bool {
    parse_sheet(id, content).is_active()
}

pub fn is_td_id(value: &str) -> bool {
    value.len() > 3
        && value.len() <= 100
        && value.starts_with("TD-")
        && value
            .bytes()
            .all(|b| b.is_ascii_alphanumeric() || b == b'-')
}

/// Every `TD-*.md` file directly under `<docs>/tech-debt/`, sorted by id.
/// Symlinks are skipped: a sheet must live in the repository.
pub fn read_sheets(docs_dir: &Path) -> Vec<TdSheet> {
    read_sheets_in(&docs_dir.join("tech-debt"))
}

/// [`read_sheets`] of a `tech-debt/` directory itself.
pub fn read_sheets_in(td_dir: &Path) -> Vec<TdSheet> {
    let Ok(entries) = std::fs::read_dir(td_dir) else {
        return Vec::new();
    };
    let mut sheets: Vec<TdSheet> = entries
        .flatten()
        .filter(|e| e.file_type().is_ok_and(|t| t.is_file()))
        .filter_map(|e| {
            let name = e.file_name().to_str()?.to_string();
            let id = name.strip_suffix(".md")?;
            if !is_td_id(id) {
                return None;
            }
            let content = std::fs::read_to_string(e.path()).ok()?;
            Some(parse_sheet(id, &content))
        })
        .collect();
    sheets.sort_by(|a, b| a.id.cmp(&b.id));
    sheets
}

/// The counted sheets that are not `TD-*`: the `CQ-*` / `PERF-*` detail files
/// of the dimension audits, parsed like any sheet. What a file leaves unsaid
/// comes from its index row, so the generated table keeps the severity the
/// dimension audit gave once it replaces that row (KT-1309).
fn read_detail_sheets(docs_dir: &Path) -> Vec<TdSheet> {
    let Ok(entries) = std::fs::read_dir(docs_dir.join("tech-debt")) else {
        return Vec::new();
    };
    let rows = docs_index_rows(docs_dir);
    entries
        .flatten()
        .filter(|e| e.file_type().is_ok_and(|t| t.is_file()))
        .filter_map(|e| {
            let name = e.file_name().to_str()?.to_string();
            let id = counted_sheet_stem(&name).filter(|id| !is_td_id(id))?;
            let content = std::fs::read_to_string(e.path()).ok()?;
            let mut sheet = parse_sheet(id, &content);
            if let Some(row) = rows.get(id) {
                let unknown = |v: &str| v.eq_ignore_ascii_case(UNKNOWN);
                if sheet.title == sheet.id {
                    sheet.title = row.title.clone().unwrap_or(sheet.title);
                }
                if unknown(&sheet.area) {
                    sheet.area = row.area.clone().unwrap_or(sheet.area);
                }
                if unknown(&sheet.severity) {
                    sheet.severity = row.severity.clone().unwrap_or(sheet.severity);
                }
                if unknown(&sheet.status) {
                    sheet.status = row.status.clone().unwrap_or(sheet.status);
                }
            }
            Some(sheet)
        })
        .collect()
}

pub fn parse_sheet(id: &str, content: &str) -> TdSheet {
    let lines: Vec<&str> = content.lines().collect();
    let fm_end = frontmatter_end(&lines);
    let front: &[&str] = fm_end.map_or(&[], |end| &lines[1..end]);
    let body = body_lines(&lines[fm_end.map_or(0, |end| end + 1)..]);

    let title = front_key(front, "description")
        .or_else(|| body_field(&body, "problem"))
        .or_else(|| first_line_under(&body, "## problem"))
        .or_else(|| {
            body.iter()
                .find_map(|l| l.trim().strip_prefix("# "))
                .map(clean)
                .filter(|h| !h.is_empty() && h != id)
        })
        .unwrap_or_else(|| id.to_string());
    let status = body_field(&body, "status")
        .or_else(|| front_key(front, "status"))
        .or_else(|| {
            front
                .iter()
                .rev()
                .find_map(|l| l.trim().strip_prefix("status:"))
                .map(clean)
                .filter(|v| !v.is_empty())
        })
        .unwrap_or_else(|| UNKNOWN.to_string());
    TdSheet {
        id: id.to_string(),
        title: truncate(&title, 160),
        area: body_field(&body, "area")
            .or_else(|| front_key(front, "area"))
            .unwrap_or_else(|| UNKNOWN.to_string()),
        severity: body_field(&body, "severity")
            .or_else(|| front_key(front, "severity"))
            .unwrap_or_else(|| UNKNOWN.to_string()),
        status,
        category: body_field(&body, "category").map(|c| c.to_lowercase()),
        decision: td_decision(content),
    }
}

fn frontmatter_end(lines: &[&str]) -> Option<usize> {
    if lines.first().is_none_or(|l| l.trim() != "---") {
        return None;
    }
    (1..lines.len()).find(|&i| lines[i].trim() == "---")
}

/// Body lines outside fenced code blocks.
fn body_lines<'a>(lines: &[&'a str]) -> Vec<&'a str> {
    let mut in_fence = false;
    let mut out = Vec::new();
    for line in lines {
        if line.trim_start().starts_with("```") {
            in_fence = !in_fence;
            continue;
        }
        if !in_fence {
            out.push(*line);
        }
    }
    out
}

/// `- **Name**: value` or `**Name:** value`, case-insensitive.
fn body_field(body: &[&str], name: &str) -> Option<String> {
    let colon_out = format!("**{name}**:");
    let colon_in = format!("**{name}:**");
    body.iter().find_map(|line| {
        let t = line.trim_start();
        let t = t
            .strip_prefix("- ")
            .or_else(|| t.strip_prefix("* "))
            .unwrap_or(t);
        let starts = |p: &str| t.get(..p.len()).is_some_and(|h| h.eq_ignore_ascii_case(p));
        let rest = if starts(&colon_out) {
            &t[colon_out.len()..]
        } else if starts(&colon_in) {
            &t[colon_in.len()..]
        } else {
            return None;
        };
        Some(clean(rest)).filter(|v| !v.is_empty())
    })
}

/// A top-level front matter key, folded block scalars included.
fn front_key(front: &[&str], key: &str) -> Option<String> {
    let prefix = format!("{key}:");
    let idx = front.iter().position(|l| l.starts_with(&prefix))?;
    let value = front[idx][prefix.len()..].trim();
    let value = if value.is_empty() || matches!(value, ">" | "|" | ">-" | "|-") {
        front[idx + 1..]
            .iter()
            .take_while(|l| l.starts_with(' ') || l.trim().is_empty())
            .map(|l| l.trim())
            .collect::<Vec<_>>()
            .join(" ")
    } else {
        value.to_string()
    };
    Some(clean(&value)).filter(|v| !v.is_empty())
}

fn first_line_under(body: &[&str], heading: &str) -> Option<String> {
    let start = body
        .iter()
        .position(|l| l.trim().to_lowercase().starts_with(heading))?;
    body[start + 1..]
        .iter()
        .map(|l| l.trim())
        .take_while(|l| !l.starts_with('#'))
        .find(|l| !l.is_empty() && !l.starts_with("<!--"))
        .map(clean)
        .filter(|v| !v.is_empty())
}

fn clean(value: &str) -> String {
    value
        .trim()
        .trim_matches(|c| matches!(c, '*' | '`' | '"' | '\''))
        .split_whitespace()
        .collect::<Vec<_>>()
        .join(" ")
}

fn truncate(value: &str, max: usize) -> String {
    if value.chars().count() <= max {
        return value.to_string();
    }
    let mut out: String = value.chars().take(max - 1).collect();
    out.push('…');
    out
}

fn cell(value: &str) -> String {
    value.replace('|', "\\|")
}

/// The TD id in the first cell of a markdown table row, link or code span
/// stripped, with the row's cells.
fn table_row(line: &str) -> Option<(String, Vec<String>)> {
    let t = line.trim();
    if !t.starts_with('|') {
        return None;
    }
    let cells: Vec<String> = t.split('|').map(|c| c.trim().to_string()).collect();
    let first = cells.get(1)?.trim_start_matches(['[', '`']);
    let id: String = first
        .chars()
        .take_while(|c| c.is_ascii_alphanumeric() || *c == '-')
        .collect();
    is_td_id(&id).then_some((id, cells))
}

/// What an index row says about a sheet that has no front matter to say it.
#[derive(Debug, Default, Clone, PartialEq, Eq)]
pub struct IndexRow {
    pub title: Option<String>,
    pub area: Option<String>,
    pub severity: Option<String>,
    pub status: Option<String>,
}

fn column(header: &[String], names: &[&str]) -> Option<usize> {
    header
        .iter()
        .position(|h| names.iter().any(|n| h.eq_ignore_ascii_case(n)))
}

/// The rows of an index file by sheet id (any `is_sheet_id` id, not only
/// `TD-`), read through the header of their table. A table without a header
/// row uses the central index layout: ID | Problem | Area | Severity | Status.
pub fn index_rows(content: &str) -> BTreeMap<String, IndexRow> {
    let mut out = BTreeMap::new();
    let mut header: Vec<String> = Vec::new();
    let mut fenced = false;
    for line in content.lines() {
        let t = line.trim();
        if t.starts_with("```") {
            fenced = !fenced;
        }
        if fenced || !t.starts_with('|') {
            header.clear();
            continue;
        }
        let cells: Vec<String> = t
            .trim_matches('|')
            .split('|')
            .map(|c| clean(c.trim()))
            .collect();
        let first = cells
            .first()
            .map(|c| c.trim_start_matches(['[', '`']))
            .unwrap_or("");
        let id: String = first
            .chars()
            .take_while(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_'))
            .collect();
        if cells
            .iter()
            .all(|c| c.chars().all(|ch| ch == '-' || ch == ':'))
        {
            continue;
        }
        if !is_sheet_id(&id) || !id.contains(|c: char| c.is_ascii_digit()) {
            if column(&cells, &["severity", "sévérité"]).is_some() {
                header = cells.iter().map(|c| c.to_lowercase()).collect();
            }
            continue;
        }
        let pick = |names: &[&str], default: usize| {
            let at = if header.is_empty() {
                Some(default)
            } else {
                column(&header, names)
            };
            at.and_then(|i| cells.get(i))
                .filter(|v| !v.is_empty() && v.as_str() != "—" && v.as_str() != "-")
                .cloned()
        };
        out.entry(id).or_insert_with(|| IndexRow {
            title: pick(&["problem", "title", "description", "issue", "finding"], 1),
            area: pick(&["area", "zone"], 2),
            severity: pick(&["severity", "sévérité"], 3),
            status: pick(&["status", "statut"], 4),
        });
    }
    out
}

/// [`index_rows`] of the central index, then of the dimension indexes: the
/// first file that gives a field wins.
pub fn docs_index_rows(docs_dir: &Path) -> BTreeMap<String, IndexRow> {
    let mut files: Vec<String> = Vec::new();
    if let Ok(central) = std::fs::read_to_string(docs_dir.join(CENTRAL_INDEX)) {
        files.push(central);
    }
    files.extend(dimension_indexes(docs_dir).into_values());
    let mut merged: BTreeMap<String, IndexRow> = BTreeMap::new();
    for content in files {
        for (id, row) in index_rows(&content) {
            let slot = merged.entry(id).or_default();
            slot.title = slot.title.take().or(row.title);
            slot.area = slot.area.take().or(row.area);
            slot.severity = slot.severity.take().or(row.severity);
            slot.status = slot.status.take().or(row.status);
        }
    }
    merged
}

/// One tech debt of a project, as the card and the review both see it
/// (KT-1309): a sheet file of `tech-debt/`, or a `TD-*` row of the central
/// index no sheet exists for.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DebtEntry {
    pub id: String,
    /// `<id>.md` when the sheet exists.
    pub file_name: Option<String>,
    /// The sheet's text; `None` without a sheet, or when it cannot be read.
    pub content: Option<String>,
    /// What the index says about it.
    pub row: Option<IndexRow>,
    pub decision: Option<TdDecision>,
}

impl DebtEntry {
    /// Rejected findings and accepted trade-offs are settled, not active debt.
    pub fn is_active(&self) -> bool {
        self.decision.is_none_or(|d| !d.leaves_index())
    }
}

/// Every debt of the project, sorted by id: the single set the project card
/// counts (its active members) and the review lists. A sheet decides over its
/// index row; a sheet that states no status takes the one of its row.
pub fn debt_entries(docs_dir: &Path) -> Vec<DebtEntry> {
    let rows = docs_index_rows(docs_dir);
    let mut entries: BTreeMap<String, DebtEntry> = BTreeMap::new();
    if let Ok(files) = std::fs::read_dir(docs_dir.join("tech-debt")) {
        for file in files.flatten() {
            if !file.file_type().is_ok_and(|t| t.is_file()) {
                continue;
            }
            let Some(name) = file.file_name().to_str().map(str::to_string) else {
                continue;
            };
            let Some(id) = counted_sheet_stem(&name).map(str::to_string) else {
                continue;
            };
            // An unreadable sheet still counts: the file is there.
            let content = std::fs::read_to_string(file.path()).ok();
            let row = rows.get(&id).cloned();
            let decision = content.as_deref().and_then(|text| {
                let sheet = parse_sheet(&id, text);
                sheet.decision.or_else(|| {
                    (sheet.status == UNKNOWN)
                        .then(|| row.as_ref()?.status.as_deref())
                        .flatten()
                        .and_then(index_status_decision)
                })
            });
            entries.insert(
                id.clone(),
                DebtEntry {
                    id,
                    file_name: Some(name),
                    content,
                    row,
                    decision,
                },
            );
        }
    }
    let central = std::fs::read_to_string(docs_dir.join(CENTRAL_INDEX)).unwrap_or_default();
    for id in index_rows(&central).into_keys().filter(|id| is_td_id(id)) {
        if entries.contains_key(&id) {
            continue;
        }
        let row = rows.get(&id).cloned();
        let decision = row
            .as_ref()
            .and_then(|r| r.status.as_deref())
            .and_then(index_status_decision);
        entries.insert(
            id.clone(),
            DebtEntry {
                id,
                file_name: None,
                content: None,
                row,
                decision,
            },
        );
    }
    entries.into_values().collect()
}

/// Ids listed in the TD rows of an index file.
pub fn listed_ids(content: &str) -> BTreeSet<String> {
    content
        .lines()
        .filter_map(table_row)
        .map(|(id, _)| id)
        .collect()
}

/// `docs/inconsistencies-*.md` files other than the central index, by name.
fn dimension_indexes(docs_dir: &Path) -> BTreeMap<String, String> {
    let Ok(entries) = std::fs::read_dir(docs_dir) else {
        return BTreeMap::new();
    };
    entries
        .flatten()
        .filter(|e| e.file_type().is_ok_and(|t| t.is_file()))
        .filter_map(|e| {
            let name = e.file_name().to_str()?.to_string();
            (name.starts_with("inconsistencies-") && name.ends_with(".md") && name != CENTRAL_INDEX)
                .then_some(name)
        })
        .filter_map(|name| {
            let content = std::fs::read_to_string(docs_dir.join(&name)).ok()?;
            Some((name, content))
        })
        .collect()
}

/// Coverage dimension a sub-audit index reports into.
fn index_dimension(index: &str) -> Option<&'static str> {
    match index {
        "inconsistencies-security.md" => Some("security"),
        "inconsistencies-accessibility.md" | "inconsistencies-rgaa.md" => Some("accessibility"),
        "inconsistencies-performance.md" => Some("performance"),
        _ => None,
    }
}

fn label_dimension(label: &str) -> Option<&'static str> {
    let l = label.trim().to_lowercase();
    if l.starts_with("security") {
        Some("security")
    } else if l.starts_with("accessibility") || l.starts_with("a11y") {
        Some("accessibility")
    } else if l.starts_with("performance") {
        Some("performance")
    } else if l.starts_with("observability") {
        Some("observability")
    } else {
        None
    }
}

/// Active sheets per coverage dimension: listed in that dimension's
/// sub-audit index, or carrying its `Category` or `Area`.
fn sheets_by_dimension(
    sheets: &[TdSheet],
    indexes: &BTreeMap<String, String>,
) -> BTreeMap<&'static str, BTreeSet<String>> {
    let mut out: BTreeMap<&'static str, BTreeSet<String>> = BTreeMap::new();
    let active: BTreeSet<&str> = sheets
        .iter()
        .filter(|s| s.is_active())
        .map(|s| s.id.as_str())
        .collect();
    for (name, content) in indexes {
        if let Some(dim) = index_dimension(name) {
            for id in listed_ids(content) {
                if active.contains(id.as_str()) {
                    out.entry(dim).or_default().insert(id);
                }
            }
        }
    }
    for sheet in sheets.iter().filter(|s| s.is_active()) {
        let tags = [sheet.category.as_deref(), Some(sheet.area.as_str())];
        for dim in tags.into_iter().flatten().filter_map(label_dimension) {
            out.entry(dim).or_default().insert(sheet.id.clone());
        }
    }
    out
}

fn render_block(
    sheets: &[TdSheet],
    indexes: &BTreeMap<String, String>,
    kept_without_sheet: &[String],
) -> String {
    let mut sources: BTreeMap<&str, Vec<&str>> = BTreeMap::new();
    for (name, content) in indexes {
        for id in listed_ids(content) {
            if let Some(sheet) = sheets.iter().find(|s| s.id == id) {
                sources.entry(sheet.id.as_str()).or_default().push(name);
            }
        }
    }
    let active: Vec<&TdSheet> = sheets.iter().filter(|s| s.is_active()).collect();
    let settled = sheets.len() - active.len();
    let mut out = vec![BLOCK_START.to_string()];
    out.push("| ID | Problem | Area | Severity | Status | Dimension index | Sheet |".into());
    out.push("|----|---------|------|----------|--------|-----------------|-------|".into());
    for sheet in &active {
        let source = sources
            .get(sheet.id.as_str())
            .map_or("—".to_string(), |names| {
                names
                    .iter()
                    .map(|n| {
                        format!(
                            "[{}]({n})",
                            n.trim_start_matches("inconsistencies-")
                                .trim_end_matches(".md")
                        )
                    })
                    .collect::<Vec<_>>()
                    .join(", ")
            });
        out.push(format!(
            "| {} | {} | {} | {} | {} | {} | [sheet](tech-debt/{}.md) |",
            sheet.id,
            cell(&sheet.title),
            cell(&sheet.area),
            cell(&sheet.severity),
            cell(&sheet.status),
            source,
            sheet.id
        ));
    }
    if active.is_empty() {
        out.push(String::new());
        out.push("_No active tech-debt item on file._".into());
    }
    if !indexes.is_empty() {
        out.push(String::new());
        let links: Vec<String> = indexes.keys().map(|n| format!("[{n}]({n})")).collect();
        out.push(format!("Dimension indexes: {}.", links.join(", ")));
    }
    if settled > 0 {
        out.push(String::new());
        out.push(format!(
            "{settled} settled sheet{} (rejected, or accepted as a decision) stay in `tech-debt/` and are not active debt.",
            if settled == 1 { "" } else { "s" }
        ));
    }
    if !kept_without_sheet.is_empty() {
        out.push(String::new());
        out.push("Listed without a sheet in `tech-debt/` (kept as written):".into());
        out.extend(kept_without_sheet.iter().cloned());
    }
    out.push(BLOCK_END.to_string());
    out.join("\n")
}

fn is_heading(line: &str) -> bool {
    line.trim_start().starts_with('#')
}

fn fence_mask(lines: &[&str]) -> Vec<bool> {
    let mut in_fence = false;
    lines
        .iter()
        .map(|l| {
            if l.trim_start().starts_with("```") {
                in_fence = !in_fence;
                true
            } else {
                in_fence
            }
        })
        .collect()
}

/// Lines `[start, end)` that the generated block replaces, and where to
/// insert it when there is nothing to replace.
enum Placement {
    Replace(usize, usize),
    InsertAt(usize, bool),
}

fn placement(lines: &[&str]) -> Placement {
    let fenced = fence_mask(lines);
    let live = |i: usize| !fenced[i];
    if let Some(start) =
        (0..lines.len()).find(|&i| live(i) && lines[i].trim().starts_with(BLOCK_START_PREFIX))
    {
        if let Some(end) =
            (start + 1..lines.len()).find(|&i| live(i) && lines[i].trim() == BLOCK_END)
        {
            return Placement::Replace(start, end + 1);
        }
    }
    let heading = (0..lines.len()).find(|&i| {
        live(i)
            && lines[i].trim().starts_with("## ")
            && lines[i].to_lowercase().contains("current list")
    });
    if let Some(h) = heading {
        let section_end = (h + 1..lines.len())
            .find(|&i| live(i) && is_heading(lines[i]))
            .unwrap_or(lines.len());
        if let Some(t) = (h + 1..section_end).find(|&i| live(i) && lines[i].trim().starts_with('|'))
        {
            let end = (t..section_end)
                .find(|&i| !lines[i].trim().starts_with('|'))
                .unwrap_or(section_end);
            return Placement::Replace(t, end);
        }
        return Placement::InsertAt(h + 1, false);
    }
    let coverage = (0..lines.len()).find(|&i| {
        live(i)
            && lines[i].trim().starts_with("## ")
            && lines[i].to_lowercase().contains("dimension coverage")
    });
    Placement::InsertAt(coverage.unwrap_or(lines.len()), true)
}

/// Rows of the replaced region whose TD has no sheet, kept verbatim as a
/// bullet so the resync never drops what a writer listed.
fn kept_rows(region: &[&str], sheets: &[TdSheet]) -> Vec<String> {
    let has_sheet = |id: &str| sheets.iter().any(|s| s.id == id);
    let mut seen = BTreeSet::new();
    let mut kept = Vec::new();
    for line in region {
        let t = line.trim();
        if let Some((id, cells)) = table_row(t) {
            // A row Kronn generated follows its sheet; only rows a writer
            // added by hand are kept.
            if !t.contains("](tech-debt/") && !has_sheet(&id) && seen.insert(id.clone()) {
                let problem = cells.get(2).map(String::as_str).unwrap_or("");
                kept.push(format!("- `{id}` — {problem}"));
            }
        } else if let Some(rest) = t.strip_prefix("- `") {
            let id: String = rest
                .chars()
                .take_while(|c| c.is_ascii_alphanumeric() || *c == '-')
                .collect();
            if is_td_id(&id) && !has_sheet(&id) && seen.insert(id) {
                kept.push(t.to_string());
            }
        }
    }
    kept
}

/// Rewrites `Dimension coverage` rows that claim no finding while active
/// sheets of that dimension exist. The previous outcome stays in the
/// evidence cell.
fn reconcile_coverage(
    lines: &mut [String],
    by_dimension: &BTreeMap<&'static str, BTreeSet<String>>,
) -> Vec<String> {
    let refs: Vec<&str> = lines.iter().map(String::as_str).collect();
    let fenced = fence_mask(&refs);
    let Some(h) = (0..lines.len()).find(|&i| {
        !fenced[i]
            && lines[i].trim().starts_with("## ")
            && lines[i].to_lowercase().contains("dimension coverage")
    }) else {
        return Vec::new();
    };
    let section_end = (h + 1..lines.len())
        .find(|&i| !fenced[i] && is_heading(&lines[i]))
        .unwrap_or(lines.len());
    let mut reconciled = Vec::new();
    for line in &mut lines[h + 1..section_end] {
        let t = line.trim();
        if !t.starts_with('|') {
            continue;
        }
        let cells: Vec<&str> = t.split('|').map(str::trim).collect();
        if cells.len() < 4 {
            continue;
        }
        let (label, outcome) = (cells[1].to_string(), cells[2].to_string());
        let Some(ids) = label_dimension(&label).and_then(|d| by_dimension.get(d)) else {
            continue;
        };
        if ids.is_empty() || outcome.to_lowercase().starts_with("findings") {
            continue;
        }
        let shown: Vec<&str> = ids
            .iter()
            .take(MAX_EVIDENCE_IDS)
            .map(String::as_str)
            .collect();
        let more = ids.len().saturating_sub(MAX_EVIDENCE_IDS);
        let list = if more > 0 {
            format!("{}, +{more} more", shown.join(", "))
        } else {
            shown.join(", ")
        };
        *line = format!(
            "| {label} | findings | {RESYNC_EVIDENCE} {} active TD{} on file after the dimension audits: {list} (previous outcome: {}) |",
            ids.len(),
            if ids.len() == 1 { "" } else { "s" },
            cell(&outcome)
        );
        reconciled.push(label);
    }
    reconciled
}

/// Rebuild the central index's TD table from the sheets. Pure: the caller
/// writes the result when it differs.
pub fn resync_content(
    content: &str,
    sheets: &[TdSheet],
    indexes: &BTreeMap<String, String>,
) -> (String, ResyncOutcome) {
    let lines: Vec<&str> = content.lines().collect();
    let place = placement(&lines);
    let region: &[&str] = match place {
        Placement::Replace(s, e) => &lines[s..e],
        Placement::InsertAt(..) => &[],
    };
    let kept = kept_rows(region, sheets);
    let block = render_block(sheets, indexes, &kept);
    let mut out: Vec<String> = Vec::with_capacity(lines.len() + sheets.len() + 8);
    match place {
        Placement::Replace(s, e) => {
            out.extend(lines[..s].iter().map(|l| l.to_string()));
            out.extend(block.lines().map(str::to_string));
            out.extend(lines[e..].iter().map(|l| l.to_string()));
        }
        Placement::InsertAt(at, with_heading) => {
            out.extend(lines[..at].iter().map(|l| l.to_string()));
            if with_heading {
                if out.last().is_some_and(|l| !l.trim().is_empty()) {
                    out.push(String::new());
                }
                out.push("## Current list".into());
            }
            out.push(String::new());
            out.extend(block.lines().map(str::to_string));
            out.push(String::new());
            out.extend(lines[at..].iter().map(|l| l.to_string()));
        }
    }
    let by_dimension = sheets_by_dimension(sheets, indexes);
    let reconciled = reconcile_coverage(&mut out, &by_dimension);
    let mut text = out.join("\n");
    if content.ends_with('\n') || content.is_empty() {
        text.push('\n');
    }
    let active = sheets.iter().filter(|s| s.is_active()).count();
    let outcome = ResyncOutcome {
        changed: text != content,
        listed: active,
        settled: sheets.len() - active,
        kept_without_sheet: kept.len(),
        reconciled_dimensions: reconciled,
        ..ResyncOutcome::default()
    };
    (text, outcome)
}

/// Settles the sheets a trusted ADR covers, then resyncs the central index
/// from `<docs>/tech-debt/`: a finding a decision explains is never listed.
pub fn resync(docs_dir: &Path, trust: crate::core::adr::Trust) -> Result<ResyncOutcome, String> {
    let adr = crate::core::adr::settle_covered_sheets(docs_dir, trust);
    let mut outcome = resync_index(docs_dir)?;
    match adr {
        Ok(adr) => {
            outcome.adr_settled = adr.settled;
            outcome.adr_not_in_force = adr.not_in_force;
            outcome.adr_problems = adr.problems;
            outcome.adr_downgraded = adr.downgraded;
        }
        Err(e) => tracing::warn!("ADR check before the tech-debt resync failed: {e}"),
    }
    Ok(outcome)
}

/// Resync `<docs>/inconsistencies-tech-debt.md` from `<docs>/tech-debt/`.
/// Leaves the file alone when it is absent or a symlink; the `unindexed_td`
/// diagnostic then reports the gap. A human-validated index is rewritten and
/// marked to reconfirm (KT-1079).
fn resync_index(docs_dir: &Path) -> Result<ResyncOutcome, String> {
    let index = docs_dir.join(CENTRAL_INDEX);
    let skip = |why: &str| {
        Ok(ResyncOutcome {
            skipped: Some(why.to_string()),
            ..ResyncOutcome::default()
        })
    };
    match std::fs::symlink_metadata(&index) {
        Err(_) => return skip("no central index"),
        Ok(m) if m.file_type().is_symlink() || !m.is_file() => {
            return skip("central index is not a regular file")
        }
        Ok(_) => {}
    }
    let content =
        std::fs::read_to_string(&index).map_err(|e| format!("read {}: {e}", index.display()))?;
    let mut sheets = read_sheets(docs_dir);
    sheets.extend(read_detail_sheets(docs_dir));
    sheets.sort_by(|a, b| a.id.cmp(&b.id));
    let has_block = content
        .lines()
        .any(|l| l.trim().starts_with(BLOCK_START_PREFIX));
    if sheets.is_empty() && !has_block {
        return skip("no tech-debt sheet");
    }
    let indexes = dimension_indexes(docs_dir);
    let (text, outcome) = resync_content(&content, &sheets, &indexes);
    if outcome.changed {
        crate::core::mcp_scanner::atomic_write(&index, &text)?;
        if let Some(project) = docs_dir.parent() {
            let rel = index
                .strip_prefix(project)
                .map(|p| p.to_string_lossy().replace('\\', "/"))
                .unwrap_or_default();
            if let Err(e) = crate::core::doc_provenance::note_write(
                project,
                &rel,
                &content,
                &text,
                crate::core::doc_provenance::DocWriter::TdIndex,
            ) {
                tracing::warn!("Human-validation provenance of {rel} not recorded: {e}");
            }
        }
    }
    Ok(outcome)
}

