// Read a saved briefing back as the form's answers (KT-1196), so reopening the
// form pre-fills it and saving again unchanged rewrites the same bytes.

use axum::{
    extract::{Path, State},
    Json,
};

use crate::models::{ApiResponse, SavedBriefing};
use crate::AppState;

/// The six questions in their order in `docs/briefing.md`.
pub(crate) const QUESTION_HEADINGS: [&str; 6] = [
    "## Purpose",
    "## Team",
    "## Maturity",
    "## External Dependencies",
    "## Traps & Fragile Areas",
    "## Additional Context",
];

/// Rendered for an empty optional question; read back as empty.
pub(crate) const ADDITIONAL_NONE: &str = "None.";

/// Sections the form writes after the six questions. A question ends at the
/// next heading listed here or in [`QUESTION_HEADINGS`]; any other heading
/// stays inside the answer, so a section the form does not know survives a
/// re-save. A new form section must be added here.
pub(crate) fn form_section_headings() -> [&'static str; 3] {
    [
        super::project_doc::FACTS_HEADING,
        super::briefing_docs::DOCS_HEADING,
        crate::core::td_tasks::BRIEFING_OPTIONS_HEADING,
    ]
}

/// The six answers as written in `docs/briefing.md`, header included.
pub(crate) fn render_questions(answers: [&str; 6]) -> String {
    let mut out = String::from(
        "# Project Briefing\n\
         > Auto-generated by Kronn briefing form (no AI call). Source: user answers.\n",
    );
    for (heading, answer) in QUESTION_HEADINGS.iter().zip(answers) {
        out.push('\n');
        out.push_str(heading);
        out.push('\n');
        out.push_str(&escape_answer(answer));
        out.push('\n');
    }
    out
}

/// A line of an answer that Kronn would read as structure: a heading, a
/// machine copy or a Kronn option line.
fn reads_as_structure(line: &str) -> bool {
    let t = line.trim();
    line.starts_with('\\')
        || t.starts_with('#')
        || t.starts_with("<!--")
        || t.eq_ignore_ascii_case(crate::core::td_tasks::BRIEFING_OPTION_LINE)
        || t.starts_with(crate::core::cross_audit::BRIEFING_OPTION_PREFIX)
}

/// Prefix such lines with `\` so an answer can never split the briefing or
/// switch an option on; [`unescape_answer`] gives the typed text back.
pub(crate) fn escape_answer(answer: &str) -> String {
    answer
        .split('\n')
        .map(|line| {
            if reads_as_structure(line) {
                format!("\\{line}")
            } else {
                line.to_string()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn unescape_answer(answer: &str) -> String {
    answer
        .split('\n')
        .map(|line| line.strip_prefix('\\').unwrap_or(line))
        .collect::<Vec<_>>()
        .join("\n")
}

/// The body under each question heading, `None` when absent. Each heading is
/// searched after the previous one, so a heading-like line inside an earlier
/// answer cannot take a later question's place.
fn question_bodies(notes: &str) -> [Option<String>; 6] {
    let mut bodies: [Option<String>; 6] = Default::default();
    let mut current: Option<usize> = None;
    let mut next = 0;
    let form_sections = form_section_headings();
    for line in notes.split_inclusive('\n') {
        let trimmed = line.trim_end();
        if let Some(k) = (next..QUESTION_HEADINGS.len()).find(|&k| QUESTION_HEADINGS[k] == trimmed)
        {
            bodies[k] = Some(String::new());
            current = Some(k);
            next = k + 1;
            continue;
        }
        if form_sections.contains(&trimmed) {
            current = None;
            continue;
        }
        if let Some(k) = current {
            if let Some(body) = bodies[k].as_mut() {
                body.push_str(line);
            }
        }
    }
    bodies
}

/// Parse a briefing into the form's answers. Missing or malformed parts are
/// left empty; nothing here fails.
pub(crate) fn parse_saved_briefing(notes: &str) -> SavedBriefing {
    let bodies = question_bodies(notes);
    let answer = |k: usize| {
        bodies[k]
            .as_deref()
            .map(|b| unescape_answer(b.trim()))
            .unwrap_or_default()
    };
    let mut additional = answer(5);
    if additional == ADDITIONAL_NONE {
        additional.clear();
    }
    SavedBriefing {
        purpose: answer(0),
        team: answer(1),
        maturity: answer(2),
        dependencies: answer(3),
        traps: answer(4),
        additional,
        project: super::project_doc::parse_answers(notes),
        existing_docs: super::briefing_docs::parse(notes),
        td_to_tasks: crate::core::td_tasks::briefing_wants_td_tasks(notes),
        cross_audit_agents: crate::core::cross_audit::briefing_cross_agents(notes)
            .unwrap_or_default(),
    }
}

/// GET /api/projects/:id/briefing/answers — the saved briefing as the form's
/// answers: `docs/briefing.md` first, then the DB notes; `null` when none.
pub async fn get_saved_briefing(
    State(state): State<AppState>,
    Path(id): Path<String>,
) -> Json<ApiResponse<Option<SavedBriefing>>> {
    let project = state
        .db
        .with_conn(move |conn| crate::db::projects::get_project(conn, &id))
        .await
        .ok()
        .flatten();
    let Some(project) = project else {
        return Json(ApiResponse::err("Project not found"));
    };
    let project_path = crate::core::scanner::resolve_host_path(&project.path);
    let notes = tokio::task::spawn_blocking(move || {
        crate::api::projects::resolve_briefing_notes(&project_path, &project.briefing_notes)
    })
    .await
    .ok()
    .flatten();
    Json(ApiResponse::ok(
        notes
            .filter(|n| !n.trim().is_empty())
            .map(|n| parse_saved_briefing(&n)),
    ))
}

